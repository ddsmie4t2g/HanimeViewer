package io.github.daisukikaffuchino.han1meviewer.logic.ph

/**
 * 首页那块大轮播的**批次表**（26.9.7）。
 *
 * ## 背景（用户原话）
 *
 * 「加一个换一批，另外 p站现在做的那个大轮播数据源加一个其主页有的『热门xx视频』下的内容」。
 * 用户选定的形态是：**不新增行** —— 把「推荐」与「主页热门」当成**同一个大轮播的两个来源**，
 * 用「换一批」在它们之间切换。
 *
 * ## 两个来源的性质完全不同，所以是「交替」而不是「先跑完一个」
 *
 * | 来源 | 一次能拿多少 | 能翻页吗 |
 * |---|---|---|
 * | `/recommended` | 21 条/页 | ✅ 实测 18+ 页（越界 404） |
 * | 主页 `#singleFeedSection` | **61 条一次性** | ❌ 主页没有分页参数、也没有加载更多接口 |
 *
 * ⚠️ 如果按「先把推荐 18 页翻完再进热门」的顺序排，用户要按 **18 次**才看得到热门那一批。
 * 所以这里**交替**：奇数次给热门、偶数次给推荐 ⇒ **按 1 次就能看到另一个来源**。
 *
 * ## 批次序号 → 取哪一批
 *
 * | n | 批次 |
 * |---|---|
 * | 0 | 推荐 第 1 页（首页首次加载填的那一批，不用再请求） |
 * | 1 | 主页热门 第 0 批 |
 * | 2 | 推荐 第 2 页 |
 * | 3 | 主页热门 第 1 批 |
 * | 4 | 推荐 第 3 页 |
 * | 5 | 主页热门 第 2 批 |
 * | 6 | 推荐 第 4 页 |
 * | 7 | 主页热门 第 0 批（热门那边只有 3 批，循环） |
 * | … | … |
 *
 * ⚠️ 「推荐」的页号会一直涨（n=2→p2, n=4→p3, n=6→p4 …），**越界时站点回 404**，
 * 由调用方（`NetworkRepo.getPhRecommendedPage` 返回空列表）回卷到第 1 页 ——
 * 别在这里封顶，因为我们并不知道站点真实有多少页（它自己也没说准）。
 *
 * 纯数学、无副作用 ⇒ 单测 [PhCarouselBatchesTest] 钉着。
 */
object PhCarouselBatches {

    /** 一批展示多少条 —— 取「推荐」一页的条数，两个来源的观感才一致。 */
    const val BATCH_SIZE = 21

    /**
     * 主页「热门色情视频」那 61 条切成几批。
     *
     * 61 / 21 ≈ 2.9 ⇒ 3 批（最后一批 19 条）。站点哪天改了这个数也不用动代码：
     * 切片越界会得到空列表，调用方会把它当成「这一批没有」——
     * 但真到那时更该做的是把这里改成按实际条数算。
     */
    const val HOMEPAGE_HOT_BATCHES = 3

    /** 一次「换一批」要取的东西。 */
    sealed interface Batch {
        /** 取「推荐」的第 [page] 页（1 起）。 */
        data class Recommended(val page: Int) : Batch

        /** 取主页热门那 61 条里的第 [index] 批（0 起，自己按 [BATCH_SIZE] 切片）。 */
        data class HomepageHot(val index: Int) : Batch
    }

    /**
     * 第 [n] 批是什么。
     *
     * [n] `<= 0` 一律当第 1 页推荐 —— 首页首次加载就是那一批，所以「换一批」从 n=1 起算。
     */
    fun batchAt(n: Int): Batch = when {
        n <= 0 -> Batch.Recommended(1)
        // 奇数 → 主页热门，且只有 HOMEPAGE_HOT_BATCHES 批，循环。
        n % 2 == 1 -> Batch.HomepageHot(((n - 1) / 2) % HOMEPAGE_HOT_BATCHES)
        // 偶数 → 推荐，页号 1 起：n=2→2, n=4→3, n=6→4 …
        else -> Batch.Recommended(2 + (n - 2) / 2)
    }
}
